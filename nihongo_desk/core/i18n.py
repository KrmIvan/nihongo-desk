def set_language(lang: str) -> None:
    global _lang
    _lang = lang if lang in ("es", "en") else "es"


def language() -> str:
    return _lang


def t(key: str, **kw) -> str:
    pair = STRINGS.get(key)
    if pair is None:
        return key
    text = pair[0] if _lang == "es" else pair[1]
    return text.format(**kw) if kw else text
